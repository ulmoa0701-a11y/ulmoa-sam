import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright-core');
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_BIN||'/usr/bin/google-chrome',args:['--no-sandbox']});
const failures=[],out=[];
const check=(v,msg)=>{if(!v)failures.push(msg)};
for(const width of [1366,768,390,360]){
 const page=await browser.newPage({viewport:{width,height:850},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const r=await page.goto('http://127.0.0.1:8765/gardens/',{waitUntil:'networkidle'});
 check(r?.ok(),'HTTP load failed '+width);
 check(await page.locator('.play-card-enhanced').count()===34,'All games absent '+width);
 const toggle=page.locator('#gardenPictureMode');
 check(await toggle.count()===1,'Toggle absent '+width);
 check(await toggle.getAttribute('aria-pressed')==='false','Default detail view failed '+width);
 await toggle.click();
 check(await toggle.getAttribute('aria-pressed')==='true','Pressed state wrong '+width);
 check(await page.locator('body.garden-picture-mode').count()===1,'Class absent '+width);
 const descHidden=await page.locator('.play-card-enhanced .play-simple-desc').first().evaluate(el=>getComputedStyle(el).display==='none');
 check(descHidden,'Descriptions not hidden in picture mode '+width);
 const first=page.locator('.play-card-enhanced:visible').first();
 check(await first.locator('a.play-start-btn').count()===1,'Play link lost '+width);
 const previews=await page.locator('.play-card-enhanced img.real-shot').count();
 check(previews===34,'Real preview images missing '+width);
 const noOver=await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2);
 check(noOver,'Horizontal overflow '+width);
 await toggle.click();
 check(await toggle.getAttribute('aria-pressed')==='false','Detail restore failed '+width);
 const restored=await page.locator('.play-card-enhanced .play-simple-desc').first().evaluate(el=>getComputedStyle(el).display!=='none');
 check(restored,'Descriptions did not return '+width);
 const search=page.locator('#gardenSearch');await search.fill('준비물');
 check(await page.locator('.play-card-enhanced:visible').count()>=1,'Search broken '+width);
 await search.fill('');
 const preview=page.locator('.play-card-enhanced:visible .play-preview-btn').first();
 await preview.click();
 check(await page.locator('.garden-preview-dialog[open]').count()===1,'Preview dialog broken '+width);
 await page.locator('.preview-close').click();
 check(await page.locator('.garden-preview-dialog[open]').count()===0,'Preview dialog does not close '+width);
 check(!errors.length,'Browser errors '+width+': '+errors.join('; '));
 out.push({width,game_count:previews,search:true,modal:true,overflow:!noOver,errors});
 await page.close();
}
await browser.close();
console.log(JSON.stringify({screens:out,failures},null,2));
if(failures.length)process.exit(1);