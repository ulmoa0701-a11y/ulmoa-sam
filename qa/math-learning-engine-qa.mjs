import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('math-garden/learning-engine.js','utf8'),context);
const L=context.window.NumberForestLearning;
assert.ok(L,'no learning engine exported');
assert.deepEqual(Array.from(L.PHASES),['explore','model','independent','transfer','review']);
const grades=[];
for(const phase of L.PHASES)grades.push(L.classifyRound({phase,attempts:0,hints:phase==='model'?1:0,model:phase==='model',completed:true,representation:phase==='transfer'?'berry':'acorn'}));
const summary=L.summarize(grades);
assert.equal(summary.attempts,5);assert.equal(summary.independent,3);
assert.equal(summary.transfer,1);assert.equal(summary.supported,1);assert.equal(summary.ready,true);
const guessed=L.classifyRound({phase:'independent',attempts:2,hints:1,model:true,completed:true});
assert.equal(guessed.independentlySolved,false,'a coached or guessed response is not an independent solution');
const guessedOnly=L.classifyRound({phase:'transfer',attempts:1,hints:0,model:false,completed:true});
assert.equal(guessedOnly.transferCandidate,false,'one wrong attempt disqualifies clean transfer');
const baseline=L.classifyRound({phase:'explore',attempts:0,hints:0});
assert.equal(baseline.independentlySolved,false,'baseline exposure is not a formal mastery judgment');
const model=L.classifyRound({phase:'model',attempts:0,hints:0,model:true});
assert.equal(model.independentlySolved,false,'imitation during a model is not counted independent');
const notReady=L.summarize([grades[0],grades[1],guessed,guessedOnly,grades[4]]);
assert.equal(notReady.ready,false);assert.equal(notReady.transfer,0);
assert.equal(L.nextTier({clean:999}),3,'legacy V2 clean-completion count must never imply verified mastery');
const p1=L.combine({},grades);
assert.equal(p1.verifiedSessions,1);assert.equal(L.nextTier(p1),5);
assert.equal(p1.supportedTotal,1);assert.equal(p1.independentTotal,3);
const p2=L.combine(p1,[grades[0],grades[1],guessed,guessedOnly,grades[4]]);
assert.equal(p2.verifiedSessions,1,'assisted attempts do not advance level');
const p3=L.combine(L.combine(p1,grades),grades);
assert.equal(p3.verifiedSessions,3);
assert.equal(L.nextTier(p3),9);
assert.equal(L.nextTier({verifiedSessions:-1}),3);
assert.equal(L.summarize([]).ready,false);
console.log('PASS learning engine: phase sequence, error classification, supported vs independent, transfer, review, tier progression, no legacy false mastery');
